/**
 * Long-form body of an initiative overlay (Figma home-desktop-info-overlay,
 * node 246:707). Optional — initiatives without it fall back to the short
 * label/title/text card content in the overlay.
 */
export type InitiativeDetail = {
  /** Bold standfirst under the separator. */
  lead: string;
  /** Two text columns under the lead: [left paragraphs, right paragraphs]. */
  columns: [string[], string[]];
  /** Button between the intro columns and the cover (Figma 355:3586). Where an
      initiative has a home of its own, this is the way out to it. */
  leadAction?: { label: string; href: string };
  /** Paragraphs under the cover image. */
  body: string[];
  feature: {
    label: string;
    heading: string;
    /** Bold opening line of the feature column. Omit where the frame has none —
        Bulgaria by Design runs the column as one block of body copy. */
    intro?: string;
    paragraphs: string[];
    /**
     * A bulleted list closing the feature column (Figma 418:2276). Distinct
     * from `checklist`, which is the ruled full-width block: these are the
     * items of the sentence the last paragraph ends on — the two McKinsey
     * figures on Дизайн зрялост — so they are a plain <ul> inside the column.
     */
    bullets?: string[];
  };
  /** Question introducing the checklist. Omit where the list follows straight
      on from the feature text instead of from a question of its own. */
  checklistHeading?: string;
  /** Bordered rows — "this is for you when…". */
  checklist: string[];
  /**
   * Where the rows sit. Default is full width below the feature block, as
   * Policy Lab and Bulgaria by Design have it. Future Makers Lab (373:4473)
   * nests them in the feature's right column instead, so its eleven topics
   * read as a continuation of the sentence above them rather than a new
   * section.
   */
  checklistInFeature?: boolean;
  /** A second feature block below the checklist (Figma 355:3316). Same shape as
      `feature`, closing the argument rather than opening it. */
  featureClosing?: {
    label: string;
    heading: string;
    paragraphs: string[];
    /** Button under the closing paragraph (373:4711). */
    action?: { label: string; href: string };
  };
  /** Closing button row. `prompt` is the drawer's own lead when the button
      opens the partner form as a side panel — the specific ask, in words.
      `form: "pilot"` opens the pilot enquiry instead of the partner form. */
  actions?: {
    label: string;
    href: string;
    variant?: "primary" | "secondary";
    prompt?: string;
    form?: "pilot";
  }[];
  /**
   * "The team behind X" panel. `members` are member slugs (the photo filename
   * stem, as used by the Notion merge) — resolved to portraits by the page.
   */
  team?: {
    heading: string;
    text: string;
    cta: { label: string; href: string };
    /** Right-aligned caption above the avatar stack. */
    creditLabel: string;
    members: string[];
  };
};

export type Initiative = {
  /**
   * Mirrors the "На сайта" checkbox in the Notion CMS. Set false to take an
   * initiative off the site — the carousel, the mega menu and its own page all
   * disappear together, because every one of them reads the same filtered list.
   * The content stays here so republishing is one word, not a rewrite.
   */
  published?: boolean;
  /**
   * The initiative's photograph. Lives here rather than on `detail` because the
   * cards and the mega menu show it too, and an initiative can have a picture
   * long before it has a long-form page — Дизайн зрялост does.
   */
  /**
   * `focal` is the CSS object-position the page hero crops around, and it
   * defaults to centre. The 1092×640 frame is far wider than most of these
   * photographs, so something always gets cut; naming the part that has to
   * survive is the only way a photograph whose subject sits low in the frame
   * (Future Makers Lab) and one shot from above (Policy Lab) can share it.
   */
  cover?: { src: string; alt: string; focal?: string };
  /**
   * Optional override for the carousel card and the mega-menu preview. Where a
   * photograph works at 240px but not as a page-wide hero — or the other way
   * round — this is the small one. Falls back to `cover`.
   */
  cardCover?: { src: string; alt: string };
  /** URL segment — locale-neutral, identical in bg and en, since the language
      toggle swaps only the locale prefix. Permanent once shipped: renaming one
      breaks any link already sent out. */
  slug: string;
  label: string;
  title: string;
  text: string;
  pattern: 1 | 2 | 3 | 4;
  cta?: { label: string; href: string };
  detail?: InitiativeDetail;
};

