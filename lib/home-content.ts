/* =============================================================================
   Locale plumbing — primitives live in ./i18n (kept content-free for proxy.ts);
   re-exported here so app code has a single import site.
============================================================================= */
export { locales, defaultLocale, hasLocale } from "./i18n";
export type { Locale } from "./i18n";

/* =============================================================================
   Notion CMS — generated by `npm run sync:bios` from the "Екип" tab of the
   Website CMS database (published rows only). Merged in here rather than
   inlined above so the member lists stay hand-editable.

   Editors own `role`, `bio` and `linkedin` in Notion; this file stays the
   source of truth for `name`, `photo` and ordering. Names in particular must
   NOT come from Notion: the slug that pairs the two sides is derived from the
   photo filename, so a rename there would silently orphan the entry rather
   than fail loudly.
============================================================================= */

type CmsLocaleFields = { name?: string; role?: string; bio?: string };
type CmsEntry = { linkedin?: string } & Partial<Record<Locale, CmsLocaleFields>>;

const cms = generatedBios as Record<string, CmsEntry>;

/** Photo path -> slug: "/figma/team/stefan-vladimirov.png" -> "stefan-vladimirov". */
const slugOf = (m: Member) => m.photo?.split("/").pop()?.replace(/\.[^.]+$/, "") ?? "";

function withCmsFields(locale: Locale, members: Member[]): Member[] {
  return members.map((m) => {
    const entry = cms[slugOf(m)];
    if (!entry) return m;
    const localized = entry[locale];
    // Spread only the fields Notion actually filled, so an empty CMS cell can
    // never blank out copy that exists here.
    return {
      ...m,
      ...(localized?.role ? { role: localized.role } : {}),
      ...(localized?.bio ? { bio: localized.bio } : {}),
      ...(entry.linkedin ? { linkedin: entry.linkedin } : {}),
    };
  });
}

/**
 * FAQ groups from the CMS, for one locale.
 *
 * The hand-written groups above stay in the file as the fallback: if the sync
 * has never run — or every row is still in draft — the section renders what it
 * always did rather than disappearing.
 */
function cmsFaqGroups(locale: Locale): FaqGroup[] | null {
  const groups = generatedFaq.groups ?? [];
  if (groups.length === 0) return null;
  return groups.map((g) => ({
    title: g.title[locale],
    items: g.items.map((it) => ({
      q: it.q[locale],
      a: it.a[locale] as FaqBlock[],
    })),
  }));
}

function applyCms(locale: Locale, dict: typeof bg): typeof bg {
  const { team } = dict;
  const faqGroups = cmsFaqGroups(locale);
  return {
    ...dict,
    faq: faqGroups ? { ...dict.faq, groups: faqGroups } : dict.faq,
    team: {
      ...team,
      board: { ...team.board, members: withCmsFields(locale, team.board.members) },
      advisory: { ...team.advisory, members: withCmsFields(locale, team.advisory.members) },
      volunteers: { ...team.volunteers, members: withCmsFields(locale, team.volunteers.members) },
    },
  };
}

const content = {
  bg: applyCms("bg", bg),
  en: applyCms("en", en),
} satisfies Record<Locale, typeof bg>;

/** Whole content shape for one locale. */
export type SiteContent = typeof bg;

/** Returns the full content dictionary for a locale. */
export function getContent(locale: Locale): SiteContent {
  return content[locale];
}

/* =============================================================================
   Initiative lookups — mirror lib/events.ts so the full page and the
   intercepted modal resolve the same entry. Synchronous: initiatives are
   hand-authored above rather than fetched.
============================================================================= */

export function getInitiative(locale: Locale, slug: string): Initiative | null {
  return getContent(locale).initiatives.items.find((i) => i.slug === slug) ?? null;
}

/**
 * Slug list for generateStaticParams. Locale-neutral by construction — both
 * dictionaries carry the same slugs — so reading the default locale is enough,
 * exactly as getEventSlugs() does.
 */
export function getInitiativeSlugs(): { slug: string }[] {
  return content[defaultLocale].initiatives.items.map((i) => ({ slug: i.slug }));
}
